"""Price bars: building them from live prices, storing them, and reading them back.

Bars are OHLC candles in two timeframes: '1m' and '1d', bucketed in UTC. Each bar
records its origin, so analysis can tell real history from made-up history:
    recorded   built here from live prices in the PriceCache
    synthetic  generated by SyntheticHistory to fill the past
    vendor     fetched from a market data provider's history
"""

from __future__ import annotations

import sqlite3
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, replace
from typing import Literal

from ..db import transaction

Timeframe = Literal["1m", "1d"]
Origin = Literal["recorded", "synthetic", "vendor"]

TIMEFRAME_SECONDS: dict[str, int] = {"1m": 60, "1d": 86400}
REAL_ORIGINS: tuple[Origin, ...] = ("recorded", "vendor")


def bucket_start(timestamp: float, timeframe: str) -> int:
    """Start of the UTC bucket that contains the timestamp."""
    seconds = TIMEFRAME_SECONDS[timeframe]
    return int(timestamp // seconds) * seconds


@dataclass(frozen=True, slots=True)
class Bar:
    ticker: str
    timeframe: Timeframe
    start_ts: int
    open: float
    high: float
    low: float
    close: float
    origin: Origin

    def to_dict(self) -> dict:
        return {
            "time": self.start_ts,
            "open": self.open,
            "high": self.high,
            "low": self.low,
            "close": self.close,
            "origin": self.origin,
        }


class BarBuilder:
    """Builds one-minute bars from price samples, one bar in progress per ticker.

    A sample with the same timestamp as the ticker's last one is not new data (the
    cache was only read again), so a stalled feed doesn't produce flat bars.
    """

    def __init__(self) -> None:
        self._bars: dict[str, Bar] = {}
        self._last_seen: dict[str, float] = {}
        self._dirty: set[str] = set()
        self._closed: list[Bar] = []

    def add(self, ticker: str, price: float, timestamp: float) -> None:
        if self._last_seen.get(ticker) == timestamp:
            return
        self._last_seen[ticker] = timestamp
        start = bucket_start(timestamp, "1m")
        current = self._bars.get(ticker)

        if current is not None and start < current.start_ts:
            return  # Out of order; that minute was already written
        if current is not None and start == current.start_ts:
            self._bars[ticker] = replace(
                current,
                high=max(current.high, price),
                low=min(current.low, price),
                close=price,
            )
        else:
            if current is not None and ticker in self._dirty:
                self._closed.append(current)  # Its last update hasn't been written yet
            self._bars[ticker] = Bar(ticker, "1m", start, price, price, price, price, "recorded")
        self._dirty.add(ticker)

    def drain(self) -> list[Bar]:
        """Bars changed since the last drain, including ones in progress."""
        bars = [*self._closed, *(self._bars[t] for t in sorted(self._dirty))]
        self._closed = []
        self._dirty = set()
        return bars


# --- Storage ---

_COLUMNS = "ticker, timeframe, start_ts, open, high, low, close, origin"

# Merge a recorded bar into whatever is stored. Writing the same bar again is
# harmless, so in-progress bars can be saved repeatedly. A day that already holds
# synthetic minutes stays synthetic, and vendor bars are never overwritten.
_MERGE = f"""
INSERT INTO price_bars ({_COLUMNS}) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
ON CONFLICT (ticker, timeframe, start_ts) DO UPDATE SET
    high = max(price_bars.high, excluded.high),
    low = min(price_bars.low, excluded.low),
    close = excluded.close,
    origin = CASE WHEN price_bars.origin = 'synthetic' THEN 'synthetic' ELSE excluded.origin END
WHERE price_bars.origin != 'vendor'
"""

_REPLACE_UNLESS_VENDOR = f"""
INSERT INTO price_bars ({_COLUMNS}) VALUES (?, ?, ?, ?, ?, ?, ?, ?)
ON CONFLICT (ticker, timeframe, start_ts) DO UPDATE SET
    open = excluded.open, high = excluded.high, low = excluded.low,
    close = excluded.close, origin = excluded.origin
WHERE price_bars.origin != 'vendor'
"""


def _row(bar: Bar) -> tuple:
    return (
        bar.ticker,
        bar.timeframe,
        bar.start_ts,
        bar.open,
        bar.high,
        bar.low,
        bar.close,
        bar.origin,
    )


def _from_row(row: sqlite3.Row) -> Bar:
    return Bar(
        row["ticker"],
        row["timeframe"],
        row["start_ts"],
        row["open"],
        row["high"],
        row["low"],
        row["close"],
        row["origin"],
    )


def write_recorded(conn: sqlite3.Connection, bars: Sequence[Bar]) -> None:
    """Save one-minute recorded bars and fold each into its day."""
    rows = []
    for bar in bars:
        rows.append(_row(bar))
        rows.append(_row(replace(bar, timeframe="1d", start_ts=bucket_start(bar.start_ts, "1d"))))
    with transaction(conn):
        conn.executemany(_MERGE, rows)


def insert_bars(conn: sqlite3.Connection, bars: Iterable[Bar]) -> None:
    """Add backfilled bars. Existing bars win, so backfill never overwrites."""
    with transaction(conn):
        conn.executemany(
            f"INSERT OR IGNORE INTO price_bars ({_COLUMNS}) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            map(_row, bars),
        )


def rollup_days(conn: sqlite3.Connection, ticker: str, day_starts: Iterable[int]) -> None:
    """Rebuild daily bars from the one-minute bars stored for those days.

    A day with any synthetic minute is synthetic; a day of only vendor minutes is
    vendor; anything else is recorded. Vendor daily bars are left alone.
    """
    daily = []
    for day in sorted(set(day_starts)):
        rows = conn.execute(
            """
            SELECT open, high, low, close, origin FROM price_bars
            WHERE ticker = ? AND timeframe = '1m' AND start_ts >= ? AND start_ts < ?
            ORDER BY start_ts
            """,
            (ticker, day, day + TIMEFRAME_SECONDS["1d"]),
        ).fetchall()
        if not rows:
            continue
        origins = {row["origin"] for row in rows}
        if "synthetic" in origins:
            origin = "synthetic"
        elif origins == {"vendor"}:
            origin = "vendor"
        else:
            origin = "recorded"
        daily.append(
            Bar(
                ticker,
                "1d",
                day,
                rows[0]["open"],
                max(row["high"] for row in rows),
                min(row["low"] for row in rows),
                rows[-1]["close"],
                origin,
            )
        )
    with transaction(conn):
        conn.executemany(_REPLACE_UNLESS_VENDOR, map(_row, daily))


def recent_bars(
    conn: sqlite3.Connection,
    ticker: str,
    timeframe: str,
    limit: int,
    origins: Sequence[str] | None = None,
) -> list[Bar]:
    """The most recent bars, oldest first, optionally only of the given origins."""
    origin_filter = ""
    params: list = [ticker, timeframe]
    if origins is not None:
        origin_filter = f"AND origin IN ({', '.join('?' * len(origins))})"
        params += list(origins)
    rows = conn.execute(
        f"""
        SELECT {_COLUMNS} FROM price_bars
        WHERE ticker = ? AND timeframe = ? {origin_filter}
        ORDER BY start_ts DESC LIMIT ?
        """,
        (*params, limit),
    ).fetchall()
    return [_from_row(row) for row in reversed(rows)]


def earliest_bar(conn: sqlite3.Connection, ticker: str, timeframe: str) -> Bar | None:
    row = conn.execute(
        f"""
        SELECT {_COLUMNS} FROM price_bars WHERE ticker = ? AND timeframe = ?
        ORDER BY start_ts LIMIT 1
        """,
        (ticker, timeframe),
    ).fetchone()
    return _from_row(row) if row else None


def prune(conn: sqlite3.Connection, timeframe: str, before_ts: int) -> int:
    """Delete bars that started before the cutoff. Returns how many went."""
    with transaction(conn):
        cursor = conn.execute(
            "DELETE FROM price_bars WHERE timeframe = ? AND start_ts < ?", (timeframe, before_ts)
        )
    return cursor.rowcount


# --- Selecting bars for analysis ---


def real_coverage_seconds(conn: sqlite3.Connection, ticker: str, timeframe: str) -> int:
    """Time spanned by recorded and vendor bars, first bar start to last bar end.

    Gaps inside the span are not subtracted.
    """
    row = conn.execute(
        """
        SELECT MIN(start_ts) AS first, MAX(start_ts) AS last FROM price_bars
        WHERE ticker = ? AND timeframe = ? AND origin IN ('recorded', 'vendor')
        """,
        (ticker, timeframe),
    ).fetchone()
    if row["first"] is None:
        return 0
    return row["last"] - row["first"] + TIMEFRAME_SECONDS[timeframe]


def effective_cutoff_days(
    cutoff_days: float | None, timeframe: str, retention_days: float
) -> float | None:
    """The span of real history after which synthetic bars stop being used.

    One-minute bars older than the retention window are deleted, so real
    one-minute coverage can never exceed it. The cutoff is capped a day short of
    it, so coverage at the edge of the window doesn't flip back and forth.
    """
    if cutoff_days is None or timeframe != "1m":
        return cutoff_days
    return min(cutoff_days, max(retention_days - 1, 1))


def bars_for_analysis(
    conn: sqlite3.Connection,
    ticker: str,
    timeframe: str,
    limit: int,
    cutoff_days: float | None,
    retention_days: float,
) -> list[Bar]:
    """Bars to compute on: synthetic ones only until real history covers the cutoff.

    cutoff_days None (the 'never' setting) always includes synthetic bars.
    """
    cutoff = effective_cutoff_days(cutoff_days, timeframe, retention_days)
    if cutoff is not None and real_coverage_seconds(conn, ticker, timeframe) >= cutoff * 86400:
        return recent_bars(conn, ticker, timeframe, limit, origins=REAL_ORIGINS)
    return recent_bars(conn, ticker, timeframe, limit)
